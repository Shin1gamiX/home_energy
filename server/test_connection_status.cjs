'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../connection-status.js'), 'utf8'), context);
const { assess, hasReadings, selectReadings, languages } = context.window.energyConnectionStatus;
const now = 1800000000;
const packet = (overrides = {}) => ({ values: { pv: 0, grid: 0, load: 0, battery: 0, soc: 0 }, status: 'stale', updated_at: now - 900, generated_at: now, ...overrides });
const health = (vpn, dongle, collector = 'up', checked_at = now) => ({ version: 1, checks: Object.fromEntries(Object.entries({ vpn, dongle, collector, inverter: 'stale' }).map(([key, state]) => [key, { state, checked_at }])) });
const state = (latest, options = {}) => assess({ latest, now, ...options });
assert.equal(state(null).kind, 'checking');
assert.equal(state(packet(), { requestFailed: true, online: false }).kind, 'viewer_offline');
assert.equal(state(packet(), { requestFailed: true }).kind, 'service_unavailable');
assert.equal(state(packet({ status: 'offline', updated_at: null })).kind, 'source_unavailable');
assert.equal(state(packet({ health: health('down', 'unknown') })).kind, 'vpn_unreachable');
assert.equal(state(packet({ health: health('up', 'down') })).kind, 'dongle_unreachable');
assert.equal(state(packet({ health: health('up', 'unknown', 'down') })).kind, 'collector_unavailable');
assert.equal(state(packet({ health: health('up', 'up') })).kind, 'inverter_stale');
assert.equal(state(packet()).kind, 'unknown', 'Legacy payloads never guess the failing equipment');
assert.equal(state(packet({ health: health('down', 'up') })).kind, 'unknown', 'Contradictory observations do not establish a cause');
assert.equal(state(packet({ health: health('down', 'up') })).checks.vpn.state, 'unknown');
const contradictoryData = health('up', 'up');
contradictoryData.checks.inverter.state = 'up';
assert.equal(state(packet({ health: contradictoryData })).checks.inverter.state, 'stale', 'Actual reading timestamps win over cached health labels');
assert.equal(state(packet({ health: health('up', 'up', 'up', now - 91) })).kind, 'unknown');
assert.equal(state(packet({ health: health('up', 'up', 'up', now + 31) })).kind, 'unknown');
assert.equal(state(packet({ health: health('up', 'up'), generated_at: now - 21 })).kind, 'unknown');
assert.equal(state(packet({ health: health('up', 'up'), status: 'live', updated_at: now - 3 })).kind, 'live');
assert.equal(state(packet({ health: health('up', 'up'), status: 'partial', updated_at: now - 3 })).kind, 'partial');
assert.equal(state(packet({ status: 'live', updated_at: now - 3 }), { online: false }).kind, 'live', 'A successful fresh fetch outweighs the browser connectivity hint');
const failed = state(packet({ health: health('up', 'up') }), { requestFailed: true });
assert.equal(failed.checks.vpn.state, 'unknown', 'Old server diagnostics are not current when this browser cannot reach the service');
assert.equal(state(packet({ status: 'live', updated_at: now + 31 })).fresh, false);
assert.equal(hasReadings(packet()), true, 'Zero is a saved reading');
assert.equal(hasReadings(packet({ values: { pv: null } })), false);
assert.equal(hasReadings(packet({ updated_at: null })), false);
const previous = packet({ updated_at: now - 30 });
assert.equal(selectReadings(previous, packet({ values: { pv: null } }), now), previous);
assert.equal(selectReadings(previous, packet({ updated_at: now - 100 }), now), previous);
assert.equal(selectReadings(previous, packet({ updated_at: now + 31 }), now), previous);
const zero = packet({ updated_at: now });
assert.equal(selectReadings(previous, zero, now), zero);
assert.equal(selectReadings(null, packet({ values: { pv: null } }), now), null);
const missingFresh = packet({ status: 'partial', updated_at: now, values: { pv: null, load: null, grid: null, battery: null, soc: null } });
assert.equal(selectReadings(previous, missingFresh, now), missingFresh, 'Fresh partial measurements must not be silently filled from old readings');
for (const lang of ['el', 'ru']) {
  assert.deepEqual(Object.keys(languages[lang]).sort(), Object.keys(languages.en).sort());
  for (const value of Object.values(languages[lang])) assert.ok(value.length > 0);
}
console.log('Connection state classification, stale evidence, conflicting signals, offline hints, zero/missing readings and translation parity passed.');
